        /// <summary>
        /// Gets whether Rust's <c>Debug</c> escapes <paramref name="codePoint"/> rather than printing it. Cost: a compare
        /// for ASCII, else a binary search of about 11 steps.
        /// </summary>
        /// <param name="codePoint">A code point in <c>[0, 0x10FFFF]</c>, surrogates included.</param>
        /// <returns>Whether the code point is escaped.</returns>
        public static bool IsEscaped(int codePoint)
        {
            if (codePoint < 0x7F)
                return codePoint < 0x20;

            // The number of boundaries at or below the code point is odd exactly inside an escaped range.
            var boundaries = Boundaries;
            var lo = 0;
            var hi = boundaries.Length;
            while (lo < hi)
            {
                var mid = (lo + hi) >>> 1;
                if (boundaries[mid] <= codePoint)
                    lo = mid + 1;
                else
                    hi = mid;
            }

            return (lo & 1) == 1;
        }

