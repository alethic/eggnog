    /// <summary>
    /// The code points Rust's <c>Debug</c> for <c>str</c> and <c>char</c> does not print as themselves: those for which
    /// <c>char::is_grapheme_extended</c> holds or <c>core::unicode::printable::is_printable</c> fails (roughly the
    /// categories Cc, Cf, Cs, Co, Cn, Zl, Zp and Zs other than the space, every Grapheme_Extend code point, and the Hangul
    /// fillers). Rust writes them as <c>\0</c>, <c>\t</c>, <c>\n</c>, <c>\r</c> or <c>\u{hex}</c>.
    /// </summary>
    /// <remarks>
    /// <para>
    /// Generated from rustc 1.99.0 (Unicode 17.0.0, <c>char::UNICODE_VERSION</c>) by formatting every code point with
    /// <c>{:?}</c>, rather than derived from .NET's Unicode tables, which are an older Unicode version, differ between the
    /// target frameworks and do not expose Grapheme_Extend. Surrogates are included: a .NET string may hold a lone one,
    /// and Rust's tables class them as unprintable (Cs). Lookup is a binary search over 1816 sorted range boundaries after
    /// an ASCII fast path.
    /// </para>
    /// <para>
    /// To regenerate for a newer Rust, collect the half-open ranges of <c>cp</c> in <c>0..=0x10FFFF</c> for which
    /// <c>char::from_u32(cp)</c> is <c>None</c>, <c>cp</c> is 0, 9, 10 or 13, or
    /// <c>format!("{:?}", c.to_string())</c> contains <c>\u{</c>, and list their starts and ends.
    /// </para>
